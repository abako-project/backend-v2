/// Non-negative integer KVN token units; JSON is always a decimal string.
#[derive(
    Debug,
    Default,
    Clone,
    Copy,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Encode,
    Decode,
    Serialize,
    Deserialize,
)]
#[serde(try_from = "String", into = "String")]
pub struct Money(u64);
impl Money {
    /// No units.
    pub const ZERO: Self = Self(0);
    /// Construct integer token units without assigning a decimal display scale.
    #[must_use]
    pub const fn new(units: u64) -> Self {
        Self(units)
    }
    /// Return integer token units.
    #[must_use]
    pub const fn units(self) -> u64 {
        self.0
    }
    /// Add amounts without wrapping.
    pub fn checked_add(self, other: Self) -> Result<Self, ValidationError> {
        self.0
            .checked_add(other.0)
            .map(Self)
            .ok_or(ValidationError::Arithmetic)
    }
    /// Subtract without creating a negative balance.
    pub fn checked_sub(self, other: Self) -> Result<Self, ValidationError> {
        self.0
            .checked_sub(other.0)
            .map(Self)
            .ok_or(ValidationError::Arithmetic)
    }
}
impl TryFrom<String> for Money {
    type Error = ValidationError;
    fn try_from(value: String) -> Result<Self, Self::Error> {
        if value.is_empty()
            || !value.bytes().all(|b| b.is_ascii_digit())
            || (value.len() > 1 && value.starts_with('0'))
        {
            return Err(ValidationError::InvalidAmount);
        }
        value
            .parse()
            .map(Self)
            .map_err(|_| ValidationError::InvalidAmount)
    }
}
impl From<Money> for String {
    fn from(value: Money) -> Self {
        value.0.to_string()
    }
}
impl fmt::Display for Money {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(f)
    }
}

