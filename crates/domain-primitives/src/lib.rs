/// Invalid wire value or checked arithmetic failure.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ValidationError {
    /// A hexadecimal identifier has an invalid length or character.
    #[error("invalid hexadecimal identifier")]
    InvalidHex,
    /// An integer exceeds its permitted range.
    #[error("{0} is outside its permitted range")]
    OutOfRange(&'static str),
    /// An amount is not a canonical unsigned decimal string.
    #[error("invalid unsigned decimal amount")]
    InvalidAmount,
    /// Arithmetic cannot be represented by the quantity.
    #[error("arithmetic overflow or underflow")]
    Arithmetic,
    /// A weekly range ends before it starts.
    #[error("week window ends before it starts")]
    ReversedWindow,
}

fn parse_hex<const N: usize>(value: &str) -> Result<[u8; N], ValidationError> {
    let value = value.strip_prefix("0x").unwrap_or(value);
    if value.len() != N * 2 || !value.is_ascii() {
        return Err(ValidationError::InvalidHex);
    }
    let mut bytes = [0; N];
    for (slot, pair) in bytes.iter_mut().zip(value.as_bytes().chunks_exact(2)) {
        let high = char::from(pair[0])
            .to_digit(16)
            .ok_or(ValidationError::InvalidHex)?;
        let low = char::from(pair[1])
            .to_digit(16)
            .ok_or(ValidationError::InvalidHex)?;
        *slot = u8::try_from(high * 16 + low).map_err(|_| ValidationError::InvalidHex)?;
    }
    Ok(bytes)
}

macro_rules! hex_type {
    ($name:ident, $size:expr, $doc:literal) => {
        #[doc = $doc]
        #[derive(
            Clone,
            Copy,
            PartialEq,
            Eq,
            PartialOrd,
            Ord,
            Hash,
            Encode,
            Decode,
            Serialize,
            Deserialize,
        )]
        #[serde(try_from = "String", into = "String")]
        pub struct $name([u8; $size]);
        impl $name {
            /// Construct from fixed-width bytes generated by the owning service.
            #[must_use]
            pub const fn from_bytes(bytes: [u8; $size]) -> Self {
                Self(bytes)
            }
            /// Borrow the canonical byte representation.
            #[must_use]
            pub const fn as_bytes(&self) -> &[u8; $size] {
                &self.0
            }
            /// Extract the canonical byte representation.
            #[must_use]
            pub const fn into_bytes(self) -> [u8; $size] {
                self.0
            }
        }
        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("0x")?;
                for byte in self.0 {
                    write!(f, "{byte:02x}")?;
                }
                Ok(())
            }
        }
        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(self, f)
            }
        }
        impl FromStr for $name {
            type Err = ValidationError;
            fn from_str(value: &str) -> Result<Self, Self::Err> {
                parse_hex(value).map(Self)
            }
        }
        impl TryFrom<String> for $name {
            type Error = ValidationError;
            fn try_from(value: String) -> Result<Self, Self::Error> {
                value.parse()
            }
        }
        impl From<$name> for String {
            fn from(value: $name) -> Self {
                value.to_string()
            }
        }
    };
}

